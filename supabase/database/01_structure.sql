DO $$ DECLARE table_name text; BEGIN
 FOREACH table_name IN ARRAY ARRAY['app_users','exceptional_on_calls','exceptional_works','public_holidays','regular_interventions','regular_on_call_periods','rh_on_call_compensation_rules','rh_period_compensation_rules','schedule_rules','team_members','teams','visas','exceptional_on_call_participants','exceptional_on_call_interventions','exceptional_on_call_visas','exceptional_work_participants','exceptional_work_visas'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
  EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon, authenticated', table_name);
 END LOOP;
END; $$;

COMMIT;
