CREATE TABLE public.exceptional_on_call_interventions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL REFERENCES public.exceptional_on_calls(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.app_users(id) ON DELETE RESTRICT,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    was_on_site boolean NOT NULL DEFAULT false,
    label text NOT NULL DEFAULT '',
    comment text NOT NULL DEFAULT '',
    ticket text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_at < ends_at)
