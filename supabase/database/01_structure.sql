    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope public.visa_scope NOT NULL,
    operation_id bigint REFERENCES public.exceptional_on_calls(id) ON DELETE CASCADE,
    participant_id bigint REFERENCES public.exceptional_on_call_participants(id) ON DELETE CASCADE,
