    'exceptional_actual_director'
);

CREATE TABLE public.app_users (
    id bigint NOT NULL,
    auth_user_id uuid NOT NULL,
    email text NOT NULL,
    display_name text DEFAULT ''::text NOT NULL,
    trigram varchar(3),
    deleted_at timestamptz,
