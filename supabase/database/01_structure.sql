CREATE TABLE public.exceptional_on_call_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL,
    participant_kind public.operation_participant_kind NOT NULL,
    user_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_at < ends_at)
);


CREATE TABLE public.exceptional_on_call_interventions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL,
    user_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    was_on_site boolean NOT NULL DEFAULT false,
    label text NOT NULL DEFAULT '',
    comment text NOT NULL DEFAULT '',
    ticket text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_at < ends_at)
);


CREATE TABLE public.exceptional_on_call_visas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope public.visa_scope NOT NULL,
    operation_id bigint,
    participant_id bigint,
    intervention_id bigint,
    signed_by_user_id bigint,
    signed_by_name text NOT NULL DEFAULT '',
    signed_at timestamptz,
    signature_value text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(operation_id, participant_id, intervention_id) = 1),
    CHECK ((signed_at IS NULL AND signed_by_user_id IS NULL AND signed_by_name = '')
        OR (signed_at IS NOT NULL AND signed_by_name <> ''))
);




CREATE TABLE public.exceptional_work_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id bigint NOT NULL,
    participant_kind public.operation_participant_kind NOT NULL,
    user_id bigint NOT NULL,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (starts_at < ends_at)
);


CREATE TABLE public.exceptional_work_visas (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope public.visa_scope NOT NULL,
    operation_id bigint,
    participant_id bigint,
    signed_by_user_id bigint,
    signed_by_name text NOT NULL DEFAULT '',
    signed_at timestamptz,
    signature_value text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (num_nonnulls(operation_id, participant_id) = 1),
    CHECK ((signed_at IS NULL AND signed_by_user_id IS NULL AND signed_by_name = '')
        OR (signed_at IS NOT NULL AND signed_by_name <> ''))
);






