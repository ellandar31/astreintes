    execute format('drop policy if exists "authenticated_insert_%I" on public.%I', table_name, table_name);
    execute format('drop policy if exists "authenticated_update_%I" on public.%I', table_name, table_name);
    execute format('drop policy if exists "authenticated_delete_%I" on public.%I', table_name, table_name);

    execute format(
      'create policy "authenticated_read_%I" on public.%I for select to authenticated using (true)',
      table_name,
      table_name
    );
    execute format(
      'create policy "authenticated_insert_%I" on public.%I for insert to authenticated with check (true)',
      table_name,
      table_name
    );
    execute format(
      'create policy "authenticated_update_%I" on public.%I for update to authenticated using (true) with check (true)',
      table_name,
      table_name
    );
    execute format(
      'create policy "authenticated_delete_%I" on public.%I for delete to authenticated using (true)',
      table_name,
      table_name
    );
  end loop;
end;
$$;

