-- Relational domain schema for the Astreintes application.
--
-- app_documents remains available as a migration bridge from the Firebase-like
-- document store. The tables below are the target model: business aggregates are
-- split into relational entities so validation, RH controls and exports can rely
-- on SQL constraints instead of JSON shape conventions.

create extension if not exists pgcrypto;

create type public.user_role as enum (
  'admin',
  'user',
  'initiator',
  'director'
);

create type public.signature_mode as enum (
  'name',
  'image',
  'draw'
);

create type public.public_holiday_source as enum (
  'api.gouv.fr',
  'manual'
);

create type public.schedule_day as enum (
  'monday',
  'tuesday',
  'wednesday',
  'thursday',
  'friday',
  'saturday',
  'sunday',
  'public_holiday'
);

create type public.exceptional_operation_type as enum (
  'on_call',
  'extra_work'
);

create type public.operation_participant_kind as enum (
  'planned',
  'actual'
);

create type public.visa_scope as enum (
  'regular_period_agent',
  'regular_period_director',
  'regular_intervention_agent',
  'exceptional_participant_agent',
  'exceptional_intervention_agent',
  'exceptional_operation_initiator',
  'exceptional_operation_director',
  'exceptional_planned_initiator',
  'exceptional_planned_director',
  'exceptional_actual_initiator',
  'exceptional_actual_director'
);

create table public.app_users (
  id bigint generated by default as identity primary key,
  auth_user_id uuid not null unique references auth.users(id) on delete cascade,
  legacy_document_id text unique,
  email text not null unique,
  display_name text not null default '',
  role public.user_role not null default 'user',
  signature_mode public.signature_mode not null default 'name',
  signature_name text not null default '',
  signature_image text not null default '',
  signature_drawing text not null default '',
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.teams (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint teams_name_not_blank check (btrim(name) <> '')
);

create table public.team_members (
  team_id bigint not null references public.teams(id) on delete cascade,
  user_id bigint not null references public.app_users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (team_id, user_id)
);

create table public.schedule_rules (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  day public.schedule_day not null,
  hour_start time not null,
  hour_end time not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint schedule_rules_hours_order check (hour_start < hour_end)
);

create table public.public_holidays (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  zone text not null,
  holiday_date date not null,
  label text not null,
  source public.public_holiday_source not null default 'manual',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (zone, holiday_date),
  constraint public_holidays_zone_not_blank check (btrim(zone) <> ''),
  constraint public_holidays_label_not_blank check (btrim(label) <> '')
);

create table public.rh_on_call_compensation_rules (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  coefficient numeric(10, 4) not null default 0,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now(),
  constraint rh_on_call_compensation_rules_label_not_blank check (btrim(label) <> '')
);

create table public.rh_period_compensation_rules (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  intervention_coefficient numeric(10, 4) not null default 0,
  work_coefficient numeric(10, 4) not null default 0,
  rest_coefficient numeric(10, 4) not null default 0,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now(),
  constraint rh_period_compensation_rules_label_not_blank check (btrim(label) <> '')
);

create table public.rh_export_settings (
  id bigint generated by default as identity primary key,
  singleton_key boolean not null default true unique,
  generation_api_url text not null default 'http://localhost:3000/v1/documents/generate',
  updated_at timestamptz not null default now(),
  constraint rh_export_settings_singleton check (singleton_key),
  constraint rh_export_settings_url_not_blank check (btrim(generation_api_url) <> '')
);

create table public.rh_export_templates (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label text not null,
  file_name text not null default '',
  template_file_name text not null default '',
  data_model_file_name text not null default '',
  generation_template jsonb,
  data_model jsonb,
  updated_at timestamptz not null default now(),
  constraint rh_export_templates_label_not_blank check (btrim(label) <> '')
);

create table public.regular_on_call_periods (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  team_id bigint references public.teams(id) on delete set null,
  user_id bigint not null references public.app_users(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  sent_to_rh_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint regular_on_call_periods_dates_order check (starts_at < ends_at)
);

create table public.regular_interventions (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  regular_period_id bigint not null references public.regular_on_call_periods(id) on delete cascade,
  user_id bigint not null references public.app_users(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  comment text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint regular_interventions_dates_order check (starts_at < ends_at)
);

create table public.exceptional_operations (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  operation_type public.exceptional_operation_type not null,
  initiator_user_id bigint references public.app_users(id) on delete set null,
  operation_manager_user_id bigint references public.app_users(id) on delete set null,
  operation_manager_name text not null default '',
  title text not null,
  planned_starts_at timestamptz,
  planned_ends_at timestamptz,
  actual_starts_at timestamptz,
  actual_ends_at timestamptz,
  sent_to_rh_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint exceptional_operations_title_not_blank check (btrim(title) <> ''),
  constraint exceptional_operations_planned_dates_order check (planned_starts_at is null or planned_ends_at is null or planned_starts_at < planned_ends_at),
  constraint exceptional_operations_actual_dates_order check (actual_starts_at is null or actual_ends_at is null or actual_starts_at < actual_ends_at)
);

create table public.exceptional_operation_participants (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  operation_id bigint not null references public.exceptional_operations(id) on delete cascade,
  participant_kind public.operation_participant_kind not null,
  user_id bigint not null references public.app_users(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint exceptional_operation_participants_dates_order check (starts_at < ends_at)
);

create table public.exceptional_interventions (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  operation_id bigint not null references public.exceptional_operations(id) on delete cascade,
  user_id bigint not null references public.app_users(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  was_on_site boolean not null default false,
  label text not null default '',
  comment text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint exceptional_interventions_dates_order check (starts_at < ends_at)
);

create table public.visas (
  id bigint generated by default as identity primary key,
  legacy_document_id text unique,
  scope public.visa_scope not null,
  regular_period_id bigint references public.regular_on_call_periods(id) on delete cascade,
  regular_intervention_id bigint references public.regular_interventions(id) on delete cascade,
  exceptional_operation_id bigint references public.exceptional_operations(id) on delete cascade,
  exceptional_participant_id bigint references public.exceptional_operation_participants(id) on delete cascade,
  exceptional_intervention_id bigint references public.exceptional_interventions(id) on delete cascade,
  signed_by_user_id bigint references public.app_users(id) on delete set null,
  signed_by_name text not null default '',
  signed_at timestamptz,
  signature_mode public.signature_mode,
  signature_value text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint visas_signed_consistency check (
    (signed_at is null and signed_by_user_id is null and signed_by_name = '')
    or
    (signed_at is not null and signed_by_name <> '')
  ),
  constraint visas_single_target check (
    num_nonnulls(
      regular_period_id,
      regular_intervention_id,
      exceptional_operation_id,
      exceptional_participant_id,
      exceptional_intervention_id
    ) = 1
  )
);

