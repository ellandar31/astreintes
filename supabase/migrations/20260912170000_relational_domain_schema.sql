create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.prevent_regular_intervention_outside_period()
returns trigger
language plpgsql
as $$
declare
  parent_period record;
begin
  select user_id, starts_at, ends_at
  into parent_period
  from public.regular_on_call_periods
  where id = new.regular_period_id;

  if parent_period.user_id is null then
    raise exception 'Regular on-call period % does not exist', new.regular_period_id;
  end if;

  if new.user_id <> parent_period.user_id
    or new.starts_at < parent_period.starts_at
    or new.ends_at > parent_period.ends_at then
    raise exception 'Regular intervention must stay inside the parent on-call period for the same user';
  end if;

  return new;
end;
$$;

create or replace function public.prevent_exceptional_intervention_outside_actual_period()
returns trigger
language plpgsql
as $$
begin
  if not exists (
    select 1
    from public.exceptional_operation_participants participant
    where participant.operation_id = new.operation_id
      and participant.participant_kind = 'actual'
      and participant.user_id = new.user_id
      and participant.starts_at <= new.starts_at
      and participant.ends_at >= new.ends_at
  ) then
    raise exception 'Exceptional intervention must stay inside an actual participant period for the same user';
  end if;

  return new;
end;
$$;

create or replace function public.prevent_rh_sent_regular_changes()
returns trigger
language plpgsql
as $$
begin
  if old.sent_to_rh_at is not null and new.sent_to_rh_at is not null then
    raise exception 'Regular on-call period already sent to RH';
  end if;

  return new;
end;
$$;

create or replace function public.prevent_rh_sent_exceptional_changes()
returns trigger
language plpgsql
as $$
begin
  if old.sent_to_rh_at is not null and new.sent_to_rh_at is not null then
    raise exception 'Exceptional operation already sent to RH';
  end if;

  return new;
end;
$$;

