drop trigger if exists check_regular_intervention_period on public.regular_interventions;
create trigger check_regular_intervention_period
before insert or update on public.regular_interventions
for each row
execute function public.prevent_regular_intervention_outside_period();

drop trigger if exists check_exceptional_intervention_actual_period on public.exceptional_interventions;
create trigger check_exceptional_intervention_actual_period
before insert or update on public.exceptional_interventions
for each row
execute function public.prevent_exceptional_intervention_outside_actual_period();

drop trigger if exists lock_regular_period_after_rh_sent on public.regular_on_call_periods;
create trigger lock_regular_period_after_rh_sent
before update on public.regular_on_call_periods
for each row
when (
  old.sent_to_rh_at is not null
  and (
    old.team_id is distinct from new.team_id
    or old.user_id is distinct from new.user_id
    or old.starts_at is distinct from new.starts_at
    or old.ends_at is distinct from new.ends_at
  )
)
execute function public.prevent_rh_sent_regular_changes();

drop trigger if exists lock_exceptional_operation_after_rh_sent on public.exceptional_operations;
create trigger lock_exceptional_operation_after_rh_sent
before update on public.exceptional_operations
for each row
when (
  old.sent_to_rh_at is not null
  and (
    old.operation_type is distinct from new.operation_type
    or old.initiator_user_id is distinct from new.initiator_user_id
    or old.operation_manager_user_id is distinct from new.operation_manager_user_id
    or old.operation_manager_name is distinct from new.operation_manager_name
    or old.title is distinct from new.title
    or old.planned_starts_at is distinct from new.planned_starts_at
    or old.planned_ends_at is distinct from new.planned_ends_at
    or old.actual_starts_at is distinct from new.actual_starts_at
    or old.actual_ends_at is distinct from new.actual_ends_at
  )
)
execute function public.prevent_rh_sent_exceptional_changes();

