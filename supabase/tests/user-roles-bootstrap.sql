CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$
  SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;
GRANT USAGE ON SCHEMA auth TO authenticated, anon;
CREATE TABLE auth.users (id uuid PRIMARY KEY, email text NOT NULL);
CREATE TYPE public.user_role AS ENUM ('admin', 'user', 'initiator', 'director');
CREATE TYPE public.signature_mode AS ENUM ('name', 'image', 'draw');
CREATE TABLE public.app_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id),
  email text NOT NULL UNIQUE, display_name text NOT NULL DEFAULT '',
  role public.user_role NOT NULL DEFAULT 'user',
  signature_mode public.signature_mode NOT NULL DEFAULT 'name',
  signature_name text NOT NULL DEFAULT '', signature_image text NOT NULL DEFAULT '',
  signature_drawing text NOT NULL DEFAULT '', last_login_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
